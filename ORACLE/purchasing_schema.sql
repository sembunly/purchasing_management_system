CREATE TABLE departments (
 id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 name VARCHAR2(120) NOT NULL,
 description VARCHAR2(500),
 is_active NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1)),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_departments_name UNIQUE(name)
);
CREATE TABLE roles (
 id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 name VARCHAR2(60) NOT NULL,
 description VARCHAR2(255),
 is_active NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1)),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_roles_name UNIQUE(name)
);
CREATE TABLE users (
 id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 department_id NUMBER(19),
 username VARCHAR2(80) NOT NULL,
 password_hash VARCHAR2(255) NOT NULL,
 full_name VARCHAR2(150) NOT NULL,
 email VARCHAR2(150),
 is_active NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1)),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_users_username UNIQUE(username),
 CONSTRAINT fk_users_department FOREIGN KEY(department_id) REFERENCES departments(id)
);
CREATE TABLE user_roles (
 id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 user_id NUMBER(19) NOT NULL,
 role_id NUMBER(19) NOT NULL,
 is_active NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1)),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT fk_user_roles_user FOREIGN KEY(user_id) REFERENCES users(id),
 CONSTRAINT fk_user_roles_role FOREIGN KEY(role_id) REFERENCES roles(id),
 CONSTRAINT uq_user_roles UNIQUE(user_id,role_id)
);
CREATE TABLE suppliers (
 id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 name VARCHAR2(150) NOT NULL,
 contact_name VARCHAR2(120),
 phone VARCHAR2(40),
 email VARCHAR2(150),
 address VARCHAR2(500),
 is_active NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1)),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE categories (
 id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 name VARCHAR2(120) NOT NULL,
 description VARCHAR2(500),
 is_active NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1)),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_categories_name UNIQUE(name)
);
CREATE TABLE products (
 id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 category_id NUMBER(19) NOT NULL,
 sku VARCHAR2(60) NOT NULL,
 name VARCHAR2(150) NOT NULL,
 unit VARCHAR2(30) DEFAULT 'PCS' NOT NULL,
 description VARCHAR2(500),
 image_data BLOB,
 image_filename VARCHAR2(255),
 image_content_type VARCHAR2(100),
 is_active NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1)),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_products_sku UNIQUE(sku),
 CONSTRAINT fk_products_category FOREIGN KEY(category_id) REFERENCES categories(id)
);
CREATE TABLE purchase_requests (
 id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 request_no VARCHAR2(40) NOT NULL,
 department_id NUMBER(19) NOT NULL,
 requested_by NUMBER(19) NOT NULL,
 approved_by NUMBER(19),
 request_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 approved_at TIMESTAMP,
 status VARCHAR2(20) DEFAULT 'DRAFT' NOT NULL,
 notes VARCHAR2(500),
 is_active NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1)),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_purchase_requests_no UNIQUE(request_no),
 CONSTRAINT chk_purchase_requests_status CHECK(status IN ('DRAFT','PENDING','APPROVED','REJECTED','CANCELLED')),
 CONSTRAINT fk_pr_department FOREIGN KEY(department_id) REFERENCES departments(id),
 CONSTRAINT fk_pr_requested_by FOREIGN KEY(requested_by) REFERENCES users(id),
 CONSTRAINT fk_pr_approved_by FOREIGN KEY(approved_by) REFERENCES users(id)
);
CREATE TABLE purchase_request_details (
 id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 purchase_request_id NUMBER(19) NOT NULL,
 product_id NUMBER(19) NOT NULL,
 quantity NUMBER(14,3) NOT NULL CHECK(quantity > 0),
 estimated_unit_price NUMBER(18,2) DEFAULT 0 NOT NULL CHECK(estimated_unit_price >= 0),
 notes VARCHAR2(255),
 is_active NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1)),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_prd_product UNIQUE(purchase_request_id,product_id),
 CONSTRAINT fk_prd_request FOREIGN KEY(purchase_request_id) REFERENCES purchase_requests(id),
 CONSTRAINT fk_prd_product FOREIGN KEY(product_id) REFERENCES products(id)
);
CREATE TABLE purchase_orders (
 id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 order_no VARCHAR2(40) NOT NULL,
 purchase_request_id NUMBER(19) NOT NULL,
 supplier_id NUMBER(19) NOT NULL,
 ordered_by NUMBER(19) NOT NULL,
 order_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 status VARCHAR2(20) DEFAULT 'DRAFT' NOT NULL,
 notes VARCHAR2(500),
 report_file BLOB,
 report_filename VARCHAR2(255),
 report_content_type VARCHAR2(100),
 is_active NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1)),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_purchase_orders_no UNIQUE(order_no),
 CONSTRAINT uq_po_request UNIQUE(purchase_request_id),
 CONSTRAINT chk_po_status CHECK(status IN ('DRAFT','ORDERED','PARTIAL','RECEIVED','CANCELLED')),
 CONSTRAINT fk_po_request FOREIGN KEY(purchase_request_id) REFERENCES purchase_requests(id),
 CONSTRAINT fk_po_supplier FOREIGN KEY(supplier_id) REFERENCES suppliers(id),
 CONSTRAINT fk_po_ordered_by FOREIGN KEY(ordered_by) REFERENCES users(id)
);
CREATE TABLE purchase_order_details (
 id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 purchase_order_id NUMBER(19) NOT NULL,
 product_id NUMBER(19) NOT NULL,
 quantity NUMBER(14,3) NOT NULL CHECK(quantity > 0),
 unit_price NUMBER(18,2) NOT NULL CHECK(unit_price >= 0),
 is_active NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1)),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_pod_product UNIQUE(purchase_order_id,product_id),
 CONSTRAINT uq_pod_id_order UNIQUE(id,purchase_order_id),
 CONSTRAINT fk_pod_order FOREIGN KEY(purchase_order_id) REFERENCES purchase_orders(id),
 CONSTRAINT fk_pod_product FOREIGN KEY(product_id) REFERENCES products(id)
);
CREATE TABLE goods_receipts (
 id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 receipt_no VARCHAR2(40) NOT NULL,
 purchase_order_id NUMBER(19) NOT NULL,
 received_by NUMBER(19) NOT NULL,
 received_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 notes VARCHAR2(500),
 is_active NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1)),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_goods_receipts_no UNIQUE(receipt_no),
 CONSTRAINT uq_gr_id_order UNIQUE(id,purchase_order_id),
 CONSTRAINT fk_gr_order FOREIGN KEY(purchase_order_id) REFERENCES purchase_orders(id),
 CONSTRAINT fk_gr_received_by FOREIGN KEY(received_by) REFERENCES users(id)
);
-- Composite FKs ensure receipt line and order line refer to the SAME purchase order.
CREATE TABLE goods_receipt_details (
 id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 goods_receipt_id NUMBER(19) NOT NULL,
 purchase_order_id NUMBER(19) NOT NULL,
 purchase_order_detail_id NUMBER(19) NOT NULL,
 quantity_received NUMBER(14,3) NOT NULL CHECK(quantity_received > 0),
 is_active NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1)),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_grd_line UNIQUE(goods_receipt_id,purchase_order_detail_id),
 CONSTRAINT fk_grd_receipt_order FOREIGN KEY(goods_receipt_id,purchase_order_id)
   REFERENCES goods_receipts(id,purchase_order_id),
 CONSTRAINT fk_grd_po_line_order FOREIGN KEY(purchase_order_detail_id,purchase_order_id)
   REFERENCES purchase_order_details(id,purchase_order_id)
);
CREATE TABLE payment_methods (
 id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 code VARCHAR2(40) NOT NULL,
 name VARCHAR2(100) NOT NULL,
 is_active NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1)),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_payment_methods_code UNIQUE(code)
);
CREATE TABLE payments (
 id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 payment_no VARCHAR2(40) NOT NULL,
 purchase_order_id NUMBER(19) NOT NULL,
 payment_method_id NUMBER(19) NOT NULL,
 paid_by NUMBER(19) NOT NULL,
 amount NUMBER(18,2) NOT NULL CHECK(amount > 0),
 payment_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 reference_no VARCHAR2(100),
 notes VARCHAR2(500),
 is_active NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1)),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT uq_payments_no UNIQUE(payment_no),
 CONSTRAINT fk_payments_order FOREIGN KEY(purchase_order_id) REFERENCES purchase_orders(id),
 CONSTRAINT fk_payments_method FOREIGN KEY(payment_method_id) REFERENCES payment_methods(id),
 CONSTRAINT fk_payments_paid_by FOREIGN KEY(paid_by) REFERENCES users(id)
);

-- FK indexes: useful for joins and to avoid locking problems when deleting parent rows.
CREATE INDEX idx_users_department ON users(department_id);
CREATE INDEX idx_user_roles_role ON user_roles(role_id);
CREATE INDEX idx_products_category ON products(category_id);
CREATE INDEX idx_pr_department ON purchase_requests(department_id);
CREATE INDEX idx_pr_requested_by ON purchase_requests(requested_by);
CREATE INDEX idx_pr_approved_by ON purchase_requests(approved_by);
CREATE INDEX idx_prd_product ON purchase_request_details(product_id);
CREATE INDEX idx_po_supplier ON purchase_orders(supplier_id);
CREATE INDEX idx_po_ordered_by ON purchase_orders(ordered_by);
CREATE INDEX idx_pod_product ON purchase_order_details(product_id);
CREATE INDEX idx_gr_order ON goods_receipts(purchase_order_id);
CREATE INDEX idx_gr_received_by ON goods_receipts(received_by);
CREATE INDEX idx_grd_po_line ON goods_receipt_details(purchase_order_detail_id,purchase_order_id);
CREATE INDEX idx_payments_order ON payments(purchase_order_id);
CREATE INDEX idx_payments_method ON payments(payment_method_id);
CREATE INDEX idx_payments_paid_by ON payments(paid_by);
CREATE INDEX idx_pr_status_date ON purchase_requests(status,request_date);
CREATE INDEX idx_po_status_date ON purchase_orders(status,order_date);

